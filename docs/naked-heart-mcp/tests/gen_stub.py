#!/usr/bin/env python3
"""Prints the public tables of gen/schema_snapshot.json as empty tables, plus the app helpers
that need them, for the local test database. Not a copy of the Platform schema: no RLS
policies, triggers or foreign keys, only the columns the views read."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SNAP = json.load(open(os.path.join(HERE, '..', 'gen', 'schema_snapshot.json')))
TYPES = {'_int4': 'int[]', '_text': 'text[]', '_uuid': 'uuid[]'}

out = []
for name, t in sorted(SNAP.items()):
    cols = []
    for c, u in t['cols']:
        typ = TYPES.get(u, u)
        extra = ''
        if c == 'id' and u == 'uuid':
            extra = ' primary key default gen_random_uuid()'
        elif c == 'id' and u == 'int8':
            extra = ' generated by default as identity primary key'
        cols.append(f'  "{c}" {typ}{extra}')
    out.append(f'create table public."{name}" (\n' + ',\n'.join(cols) + '\n);')
    out.append(f'alter table public."{name}" enable row level security;')
    out.append(f'alter table public."{name}" force row level security;')
    out.append(f'grant all on public."{name}" to authenticated, service_role;')

out.append("""
create function app.uid() returns uuid language sql stable set search_path = public, app, pg_temp as $$
  select nullif(coalesce(current_setting('request.jwt.claim.sub', true),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'),
    current_setting('app.user_id', true)), '')::uuid $$;
create function app.is_franchisor() returns boolean language sql stable security definer
  set search_path = public, app, pg_temp as $$
  select exists (select 1 from membership m where m.user_id = app.uid() and m.active and m.role = 'franchisor_admin') $$;
create function app.manager_farm_ids() returns uuid[] language sql stable security definer
  set search_path = public, app as $$
  select coalesce(array_agg(distinct m.farm_id), '{}') from membership m
   where m.user_id = app.uid() and m.active and m.role in ('farm_admin','farm_manager','office') and m.farm_id is not null $$;
create function app.is_farm_manager(p_farm uuid) returns boolean language sql stable
  set search_path = public, app, pg_temp as $$
  select app.is_franchisor() or (p_farm is not null and p_farm = any(app.manager_farm_ids())) $$;
""")
print('\n'.join(out))
